"""Train every model, refresh derived data, and write ai/models/REPORT.md.

`python store.py train` and the nightly job both call train_all().
"""
from __future__ import annotations

import json
import time
from datetime import datetime, timezone

from ai import common
from ai.common import data_hash, load_meta, save_artifact

STEPS = ["fraud", "sentiment", "forecasting", "segmentation", "recommendations", "intents", "snapcheck"]


def _setup_django():
    import os

    import django
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
    django.setup()


def evaluate_fake_reviews() -> dict:
    """Fake-review heuristics are rules (not trained); evaluate them against the injected campaigns."""
    from ai.datasets import truth
    from backend.folder_two_services.reviews.models import Review
    from config.loader import business

    gt = truth("fake_reviews")
    if gt is None:
        return {"note": "no ground truth file (seed first)"}
    fake = set(zip(gt["fake_email"], gt["sku"]))
    rows = list(Review.objects.values_list("user__email", "product__sku", "fake_score", "status"))
    t = business()["reviews"]["fake"]["flag_threshold"]
    y = [((e, s) in fake) for e, s, _, _ in rows]
    flagged = [score >= t for _, _, score, _ in rows]
    tp = sum(a and b for a, b in zip(y, flagged))
    metrics = {"n_reviews": len(rows), "n_injected_fake": sum(y), "n_flagged": sum(flagged),
               "precision": tp / max(1, sum(flagged)), "recall": tp / max(1, sum(y)),
               "flag_threshold": t}
    save_artifact("fake_review_heuristics", {"rules": business()["reviews"]["fake"]},
                  params=business()["reviews"]["fake"], metrics=metrics, data_hash_value=data_hash(rows),
                  notes="Rule-based heuristics (weights in config/business.yaml), evaluated on injected campaigns.")
    return metrics


def evaluate_elasticity() -> dict:
    """Compare price-sensitivity estimates from past promotions with the generator's true values."""
    from ai.datasets import truth
    from backend.folder_one_core.catalog.models import Category
    from backend.folder_two_services.discounts.suggest import estimate_elasticity

    gt = truth("promotions")
    est = {c.slug: estimate_elasticity(c) for c in Category.objects.all()}
    out = {}
    for slug, e in est.items():
        true = float(gt[gt["category_slug"] == slug]["true_elasticity"].mean()) if gt is not None else None
        out[slug] = {"estimated": e["elasticity"], "n_promotions": e["n_promotions"], "method": e["method"],
                     "true_mean": round(true, 3) if true is not None else None}
    errs = [abs(v["estimated"] - v["true_mean"]) for v in out.values() if v["true_mean"] is not None]
    metrics = {"per_category": out, "mean_abs_error": sum(errs) / len(errs) if errs else None}
    save_artifact("price_elasticity", est, params={}, metrics=metrics, data_hash_value=data_hash(out),
                  notes="Estimated from order history around past promotions (no model fit).")
    return metrics


def train_all(only: list[str] | None = None) -> dict:
    """Train all (or `only`) models, then refresh data that depends on them."""
    from importlib import import_module

    results, timings = {}, {}
    for step in STEPS:
        if only and step not in only:
            continue
        t0 = time.time()
        results[step] = import_module(f"ai.train_{step}").train()
        timings[step] = round(time.time() - t0, 1)
        print(f"  trained {step} in {timings[step]}s")
    # Derived data refreshed with the new models
    from backend.folder_two_services.reviews.intelligence import analyse_all
    from backend.folder_two_services.segmentation.service import assign_segments
    if not only or "segmentation" in only:
        results["segments_assigned"] = assign_segments()
    if not only or "sentiment" in only:
        results["reviews_analysed"] = analyse_all()
        results["fake_review_heuristics"] = evaluate_fake_reviews()
    if not only or "forecasting" in only:
        results["price_elasticity"] = evaluate_elasticity()
    write_report()
    return {"timings": timings, "steps": list(timings)}


def _fmt(v):
    if isinstance(v, float):
        return f"{v:.3f}"
    return "—" if v is None else str(v)


def write_report() -> None:
    metas = {n: load_meta(n) for n in STEPS + ["fake_review_heuristics", "price_elasticity"]}
    L = ["# AI model report", "",
         f"_Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC by `python store.py train`._", "",
         "> **All metrics below come from synthetic data** generated by `ai/generators.py` from "
         "`config/ml.yaml` (seeded, reproducible). They show that each model learns the structure that was "
         "deliberately put into the data; they say nothing about performance on real customers.", ""]

    def section(title, name, rows, extra=""):
        m = metas.get(name)
        L.append(f"## {title}")
        if not m:
            L.extend(["", "_Not trained._", ""])
            return
        L.append("")
        L.append(f"Artifact `ai/models/{name}.joblib` · trained {m['trained_at']} · data hash `{m['data_hash']}`")
        L.append("")
        L.append("| Metric | Model | Baseline |")
        L.append("|---|---|---|")
        for label, a, b in rows:
            L.append(f"| {label} | {_fmt(m['metrics'].get(a) if a else None)} | {_fmt(m['metrics'].get(b) if b else None)} |")
        if extra:
            L.extend(["", extra(m) if callable(extra) else extra])
        if m.get("notes"):
            L.extend(["", f"Note: {m['notes']}"])
        L.append("")

    f = metas.get("fraud")
    section("Fraud risk score (selected model vs. config-weighted rules)", "fraud", [
        ("ROC AUC (test, newest 25% of orders)", "roc_auc_model", "roc_auc_baseline_rules"),
        ("Average precision", "avg_precision_model", "avg_precision_baseline_rules"),
        (f"Precision within review budget ({_fmt(f and f['metrics']['review_budget'])} of orders)",
         "precision_at_budget_model", "precision_at_budget_baseline_rules"),
        ("Recall within review budget", "recall_at_budget_model", "recall_at_budget_baseline_rules"),
        ("Fraud rate in test set", "fraud_rate_test", None),
        ("Share of test orders scored HIGH (→ ON_HOLD)", "share_test_high", None),
        ("Share of test orders scored MEDIUM (→ OTP)", "share_test_medium", None),
    ], lambda m: (f"Selected model: **{m['metrics'].get('chosen_model')}** (validation average precision "
                  f"{m['metrics'].get('validation_avg_precision')}). The 0–100 score is scaled so that the review "
                  f"budget's share of orders lands at or above the HIGH threshold."))
    section("Review sentiment (TF-IDF + logistic regression vs. majority class)", "sentiment", [
        ("Accuracy", "accuracy_model", "accuracy_baseline_majority"),
        ("Macro F1", "macro_f1_model", "macro_f1_baseline_majority"),
    ], lambda m: "Per class: " + json.dumps(m["metrics"].get("per_class")))
    section("Demand forecasting (best model per product vs. moving average)", "forecasting", [
        ("WAPE, evaluation window (selected per product)", "wape_best_per_product", "wape_moving_average"),
        ("MAPE (non-zero days)", "mape_best_per_product", "mape_moving_average"),
        ("WAPE Holt-Winters for all products", "wape_holt_winters", None),
        ("WAPE ridge calendar for all products", "wape_ridge_calendar", None),
        ("WAPE seasonal naive for all products", "wape_seasonal_naive", None),
    ], lambda m: (f"Models chosen per product (rolling-origin selection windows): {m['metrics'].get('chosen_models')}. "
                  f"Evaluation window: {m['metrics'].get('evaluation_window')} (not used for selection)."))
    section("Customer segmentation (RFM + K-Means vs. RFM quantile rules)", "segmentation", [
        ("Silhouette", "silhouette_kmeans", "silhouette_baseline_rules"),
        ("Adjusted Rand index vs. hidden generator segments", "ari_vs_hidden_segments_kmeans",
         "ari_vs_hidden_segments_baseline_rules"),
    ], lambda m: (f"Cluster sizes: {m['metrics'].get('cluster_sizes')}\n\n"
                  f"Hidden generator segments inside each named cluster: "
                  f"{m['metrics'].get('hidden_segment_mix_per_cluster')}"))
    r = metas.get("recommendations")
    k = r["metrics"]["k"] if r else 10
    section("Hybrid recommendations (leave-last-order-out)", "recommendations", [
        (f"Precision@{k}", f"precision_at_{k}_hybrid", f"precision_at_{k}_baseline_popularity"),
        (f"NDCG@{k}", f"ndcg_at_{k}_hybrid", f"ndcg_at_{k}_baseline_popularity"),
        (f"Precision@{k} collaborative only", f"precision_at_{k}_collaborative_only", None),
        (f"Precision@{k} content only", f"precision_at_{k}_content_only", None),
    ], lambda m: f"Evaluated on {m['metrics'].get('n_eval_users')} users. Baseline = popularity ranking.")
    section("Assistant intent classifier (fallback when no LLM key)", "intents", [
        ("Accuracy (held-out templates)", "accuracy_model", "accuracy_baseline_keywords"),
        ("Macro F1", "macro_f1_model", "macro_f1_baseline_keywords"),
        ("Accuracy, restricted to the request's channel (as used in the app)", "accuracy_model_channel_aware", None),
        ("Macro F1, channel-restricted", "macro_f1_model_channel_aware", None),
    ])
    s = metas.get("snapcheck")
    clip_note = ("**CLIP could not be loaded in this environment, so SnapCheck and search-by-photo use the "
                 "lightweight fallback embedding (colour histogram + gradient orientations + thumbnail).** "
                 "Install `requirements-clip.txt` with network access to the Hugging Face hub to use CLIP; "
                 "re-run `python store.py train` to recalibrate thresholds for it."
                 if s and not s["metrics"].get("is_clip") else "Pretrained CLIP in use (not trained here).")
    section("SnapCheck / search by photo (calibration only)", "snapcheck", [
        ("ROC AUC genuine vs. different product", "roc_auc", None),
        ("False MATCH rate (different product accepted)", "false_match_rate", None),
        ("False MISMATCH rate (genuine photo flagged)", "false_mismatch_rate", None),
        ("Genuine photos left UNCERTAIN", "uncertain_rate_genuine", None),
        ("Photo search top-1 accuracy", "photo_search_top1", "photo_search_top1_baseline_random"),
        ("Photo search top-5 accuracy", "photo_search_top5", None),
    ], lambda m: f"Method: **{m['metrics']['method']}**. Thresholds: match ≥ {m['metrics']['match_threshold']:.3f}, "
                 f"mismatch < {m['metrics']['mismatch_threshold']:.3f}.\n\n" + clip_note)
    section("Fake-review heuristics (rules, evaluated on injected campaigns)", "fake_review_heuristics", [
        ("Precision of FLAGGED", "precision", None), ("Recall of injected fakes", "recall", None),
        ("Injected fake reviews", "n_injected_fake", None), ("Flagged reviews", "n_flagged", None),
    ])
    e = metas.get("price_elasticity")
    L.append("## Price sensitivity from past promotions (discount suggestions)")
    L.append("")
    if e:
        L.append("| Category | Estimated elasticity | True mean (generator) | Promotions used | Method |")
        L.append("|---|---|---|---|---|")
        for cat, v in e["metrics"]["per_category"].items():
            L.append(f"| {cat} | {_fmt(v['estimated'])} | {_fmt(v['true_mean'])} | {v['n_promotions']} | {v['method']} |")
        L.append("")
        L.append(f"Mean absolute error: {_fmt(e['metrics']['mean_abs_error'])}")
    L.append("")
    (common.MODELS_DIR / "REPORT.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    _setup_django()
    print(train_all())
