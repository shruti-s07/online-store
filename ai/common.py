"""Artifact storage: every model is saved with joblib next to a metadata JSON."""
from __future__ import annotations

import hashlib
import json
import platform
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from config.loader import env, project_path

# Where artifacts and hidden ground-truth files live (tests point these at temp dirs)
MODELS_DIR = project_path(env("AI_MODELS_DIR"))
DATA_DIR = project_path(env("AI_DATA_DIR"))


def data_hash(*frames) -> str:
    h = hashlib.sha256()
    for f in frames:
        if isinstance(f, pd.DataFrame | pd.Series):
            h.update(pd.util.hash_pandas_object(f, index=False).values.tobytes())
        elif isinstance(f, np.ndarray):
            h.update(np.ascontiguousarray(f).tobytes())
        else:
            h.update(json.dumps(f, sort_keys=True, default=str).encode())
    return h.hexdigest()[:16]


def _jsonable(o):
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items()}
    if isinstance(o, list | tuple):
        return [_jsonable(v) for v in o]
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, np.floating):
        return None if np.isnan(o) else round(float(o), 6)
    if isinstance(o, float):
        return None if np.isnan(o) else round(o, 6)
    return o


def models_dir() -> Path:
    return MODELS_DIR


def save_artifact(name: str, obj, *, params: dict, metrics: dict, data_hash_value: str, notes: str = "") -> dict:
    d = models_dir()
    d.mkdir(parents=True, exist_ok=True)
    joblib.dump(obj, d / f"{name}.joblib", compress=3)
    meta = {
        "name": name,
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "data_hash": data_hash_value,
        "data_source": "synthetic (generated by ai/generators.py from config/ml.yaml)",
        "params": _jsonable(params),
        "metrics": _jsonable(metrics),
        "notes": notes,
        "python": platform.python_version(),
    }
    (d / f"{name}_meta.json").write_text(json.dumps(meta, indent=2))
    return meta


_cache: dict[str, tuple[float, object]] = {}


def load_artifact(name: str):
    """Load a model, reloading automatically when the file changes (e.g. nightly retrain)."""
    path = models_dir() / f"{name}.joblib"
    if not path.exists():
        return None
    mtime = path.stat().st_mtime
    hit = _cache.get(str(path))
    if hit and hit[0] == mtime:
        return hit[1]
    obj = joblib.load(path)
    _cache[str(path)] = (mtime, obj)
    return obj


def load_meta(name: str) -> dict | None:
    path = models_dir() / f"{name}_meta.json"
    return json.loads(path.read_text()) if path.exists() else None


def artifact_path(name: str) -> Path:
    return models_dir() / f"{name}.joblib"
